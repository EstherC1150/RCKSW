"use client";

import Image from "next/image";
import { TComponentFormData } from "@/app/_types/manage/manage.types";
import React, { useState, useEffect, useRef } from "react";
import { createPortal } from "react-dom";
import FbxThumbnailGenerator, { FbxThumbnailGeneratorRef } from "../../_components/common/FbxThumbnailGenerator";
import VideoThumbnail, { isVideoThumbnail, isSupportedVideoFile } from "../../_components/common/VideoThumbnail";
import UploadProgressOverlay from "../../_components/common/UploadProgressOverlay";
import { UploadProgress } from "@/app/utils/api";

import { useAlertStore } from "@/app/stores/alertStore";
import { X, Upload, Plus, Trash2, Camera, Video, FileText } from "lucide-react";

// 카테고리 타입 정의
interface Category {
  id: number;
  name: string;
}

interface ComponentModalProps {
  isOpen: boolean;
  onClose: () => void;
  onSubmit: (formData: TComponentFormData, onProgress?: (progress: UploadProgress) => void) => Promise<boolean | void> | void;
  categories: Category[];
  type: "vc_plugin" | "ns_plugin" | "vc_model" | "ns_model" | "etc";
}

const ComponentModal = ({
  isOpen,
  onClose,
  onSubmit,
  type,
}: ComponentModalProps) => {
  const [formData, setFormData] = useState<TComponentFormData>({
    thumbnail: null,
    componentName: "",
    version: "0.0.1",
    description: "",
    features: "",
    environment: "",
    sourceFile: null,
    fbxFile: null,
    additionalFiles: [],
    categoryId: "",
    subCategoryId: "",
    type: type,
    modelType: "component",
  });
  const [errors, setErrors] = useState<Record<string, string>>({});
  const [thumbnailPreview, setThumbnailPreview] = useState<string | null>(null);
  const [iconPreview, setIconPreview] = useState<string | null>(null);
  const [autoGeneratedThumbnail, setAutoGeneratedThumbnail] = useState<string | null>(null);
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [uploadProgress, setUploadProgress] = useState<UploadProgress | null>(null);
  const [isMounted, setIsMounted] = useState(false);
  const fbxGenRef = useRef<FbxThumbnailGeneratorRef>(null);

  useEffect(() => {
    setIsMounted(true);
  }, []);

  // 모달이 열릴 때마다 폼 초기화
  useEffect(() => {
    if (isOpen) {
      setFormData({
        thumbnail: null,
        componentName: "",
        version: "0.0.1",
        description: "",
        features: "",
        environment: "",
        sourceFile: null,
        fbxFile: null,
        additionalFiles: [],
        categoryId: "",
        subCategoryId: "",
        type: type,
      });
      setThumbnailPreview(null);
      setIconPreview(null);
      setAutoGeneratedThumbnail(null);
      setIsSubmitting(false);
      setErrors({});
    }
  }, [isOpen, type]);

  const handleInputChange = (
    e: React.ChangeEvent<
      HTMLInputElement | HTMLTextAreaElement | HTMLSelectElement
    >
  ) => {
    const { name, value } = e.target;

    // 타입이 변경되는 경우 모든 필드와 파일 초기화
    if (name === "type") {
      setFormData({
        thumbnail: null,
        componentName: "",
        version: "0.0.1",
        description: "",
        features: "",
        environment: "",
        sourceFile: null,
        fbxFile: null,
        additionalFiles: [],
        categoryId: "",
        subCategoryId: "",
        type: value as TComponentFormData["type"],
        modelType: "component",
      });
      setThumbnailPreview(null);
      setIconPreview(null);
      setAutoGeneratedThumbnail(null);
      setErrors({});
      return;
    }

    setFormData((prev) => ({
      ...prev,
      [name]: value,
    }));

    if (errors[name]) {
      setErrors((prev) => {
        const next = { ...prev };
        delete next[name];
        return next;
      });
    }
  };

  // 추가 파일 다중 선택 핸들러
  const handleAdditionalFilesChange = (e: React.ChangeEvent<HTMLInputElement>) => {
    if (e.target.files && e.target.files.length > 0) {
      const selectedFiles = Array.from(e.target.files);
      setFormData((prev) => ({
        ...prev,
        additionalFiles: [...(prev.additionalFiles || []), ...selectedFiles],
      }));
      e.target.value = ""; // 동일 파일 재선택 가능하게 초기화
    }
  };

  // 추가 파일 개별 삭제 핸들러
  const handleRemoveAdditionalFile = (indexToRemove: number) => {
    setFormData((prev) => ({
      ...prev,
      additionalFiles: (prev.additionalFiles || []).filter((_, idx) => idx !== indexToRemove),
    }));
  };

  const handleFileChange = (e: React.ChangeEvent<HTMLInputElement>) => {
    const { name, files } = e.target;
    const { showAlert } = useAlertStore.getState();

    // 사용자가 새로운 파일(또는 올바른 파일)을 업로드하면 해당 필드의 에러 문구 즉시 지우기
    if (errors[name]) {
      setErrors((prev) => {
        const next = { ...prev };
        delete next[name];
        return next;
      });
    }

    if (files && files.length > 0) {
      const file = files[0];
      const ext = file.name.split('.').pop()?.toLowerCase();
      
      if (name === "iconFile") {
        if (!['svg', 'png', 'jpeg', 'jpg'].includes(ext || '')) {
          showAlert('Icon 파일은 svg, png, jpeg, jpg 확장자만 업로드 가능합니다.', { title: '파일 확장자 오류', type: 'warning' });
          e.target.value = '';
          return;
        }
      }

      // VC Model 확장자 체크
      if (formData.type === "vc_model") {
        if (name === "sourceFile" && ext !== "vcmx") {
          showAlert("VC Model의 소스 파일은 .vcmx 확장자만 가능합니다.", { title: '파일 확장자 오류', type: 'warning' });
          e.target.value = "";
          return;
        }
        if (name === "fbxFile" && ext !== "fbx") {
          showAlert("FBX 파일은 .fbx 확장자만 가능합니다.", { title: '파일 확장자 오류', type: 'warning' });
          e.target.value = "";
          return;
        }
      }

      setFormData((prev) => ({
        ...prev,
        [name]: file,
      }));

      // 썸네일 이미지인 경우 미리보기 생성
      if (name === "thumbnail") {
        const reader = new FileReader();
        reader.onload = () => {
          setThumbnailPreview(reader.result as string);
          setAutoGeneratedThumbnail(null); // 수동 썸네일 선택 시 자동 생성 썸네일 제거
        };
        reader.readAsDataURL(files[0]);
      }

      // 아이콘 이미지인 경우 미리보기 생성
      if (name === "iconFile") {
        const reader = new FileReader();
        reader.onload = () => {
          setIconPreview(reader.result as string);
        };
        reader.readAsDataURL(files[0]);
      }

      // FBX 파일인 경우 (Model 타입)
      if (name === "fbxFile") {
        setAutoGeneratedThumbnail(null);
        setThumbnailPreview(null);
      }
    
      // 소스 파일이 fbx인 경우 기존 썸네일 제거
      if (name === "sourceFile") {
        setAutoGeneratedThumbnail(null); // 새 파일 선택 시 기존 썸네일 제거
        setThumbnailPreview(null); // 수동 썸네일도 제거
      }
    }
  };

  const handleFeatureChange = (value: string) => {
    setFormData({
      ...formData,
      features: value,
    });
  };

  const validateForm = () => {
    const newErrors: Record<string, string> = {};
    const { showAlert } = useAlertStore.getState();

    // 1. 필수 파일(소스/설치 파일) 유무 우선 검증
    if (!formData.sourceFile) {
      newErrors.sourceFile = "소스/실행 파일은 필수입니다.";
      setErrors(newErrors);
      showAlert(
        formData.type === "vc_model"
          ? "VCMX 소스 파일 첨부가 필수입니다."
          : formData.type === "vc_plugin"
          ? "설치파일(소스 파일) 첨부가 필수입니다."
          : "파일 첨부가 필수입니다.",
        { title: "필수 파일 누락", type: "warning" }
      );
      return false;
    }

    // 2. VC PlugIn 필수 동영상 썸네일 검증
    if (formData.type === "vc_plugin" && !formData.thumbnail) {
      showAlert(
        "VC PlugIn 등록 시에는 MP4 또는 WebM 동영상 썸네일 첨부가 필수입니다.",
        { title: "썸네일 필수", type: "warning" }
      );
      return false;
    }

    setErrors({});
    return true;
  };

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (isSubmitting) return;

    if (validateForm()) {
      setIsSubmitting(true);
      try {
        const finalFormData = { ...formData };
          
        if (!finalFormData.thumbnail && !thumbnailPreview && !autoGeneratedThumbnail && finalFormData.fbxFile && fbxGenRef.current) {
            try {
                const dataUrl = await fbxGenRef.current.generateThumbnail();
                if (dataUrl && typeof dataUrl === 'string') {
                    const arr = dataUrl.split(',');
                    const mimeMatch = arr[0].match(/:(.*?);/);
                    if (mimeMatch) {
                        const mime = mimeMatch[1];
                        const bstr = atob(arr[1]);
                        let n = bstr.length;
                        const u8arr = new Uint8Array(n);
                        while (n--) {
                            u8arr[n] = bstr.charCodeAt(n);
                        }
                        const file = new File([u8arr], `thumbnail_${Date.now()}.png`, { type: mime });
                        finalFormData.thumbnail = file;
                    }
                }
            } catch (error) {
                console.error("자동 캡처 실패:", error);
            }
        }

        setUploadProgress({ loaded: 0, total: 100, percent: 0 });
        await onSubmit(finalFormData, (progress) => {
          setUploadProgress(progress);
        });
        // 폼 초기화 및 미리보기 초기화
        setThumbnailPreview(null);
        setIconPreview(null);
        setUploadProgress(null);
      } catch (err) {
        console.error("제출 에러:", err);
      } finally {
        setIsSubmitting(false);
        setUploadProgress(null);
      }
    }
  };

  if (!isOpen || !isMounted || typeof document === "undefined") return null;

  return createPortal(
    <div className="fixed inset-0 bg-black/60 dark:bg-black/75 backdrop-blur-xs flex items-center justify-center z-[9999] p-4">
      {/* 업로드 중 로딩 및 프로그레스 오버레이 */}
      <UploadProgressOverlay
        isSubmitting={isSubmitting}
        progress={uploadProgress}
      />
      <div className="bg-card rounded-2xl w-full max-w-[760px] max-h-[88vh] flex flex-col border border-black/[0.08] dark:border-white/[0.1] shadow-2xl overflow-hidden">
        {/* 상단 모달 헤더 */}
        <div className="px-7 pt-6 pb-5 border-b border-black/[0.06] dark:border-white/[0.08] flex items-center justify-between shrink-0 bg-card">
          <div>
            <h2 className="text-lg font-bold text-foreground tracking-tight">새 컴포넌트 등록</h2>
            <p className="text-xs text-muted mt-1.5">컴포넌트 또는 모델의 메타데이터와 파일을 등록합니다.</p>
          </div>
          <button
            type="button"
            onClick={onClose}
            disabled={isSubmitting}
            className="w-8 h-8 rounded-xl flex items-center justify-center text-muted hover:text-foreground hover:bg-card-hover transition-colors cursor-pointer"
            aria-label="닫기"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* 본문 폼 스크롤 영역 */}
        <form onSubmit={handleSubmit} className="flex-1 overflow-y-auto flex flex-col">
          <div className="px-7 pt-7 pb-8 space-y-7 flex-1">
            {/* 1. 기본 정보 */}
            <div>
              <div className="mb-3.5">
                <span className="text-xs font-bold uppercase tracking-wider text-muted">기본 정보</span>
              </div>
              
              <div className="space-y-4">
                <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                  <div>
                    <label className="block text-xs font-semibold text-foreground mb-2">타입 선택</label>
                    <select
                      name="type"
                      value={formData.type}
                      onChange={handleInputChange}
                      className="w-full bg-input text-foreground px-3.5 py-2.5 rounded-xl border border-black/[0.08] dark:border-white/[0.08] focus:bg-background focus:ring-2 focus:ring-primary/20 focus:border-primary outline-none transition-all text-xs"
                    >
                      <option className="bg-card text-foreground" value="vc_plugin">VC PlugIn</option>
                      <option className="bg-card text-foreground" value="ns_plugin">NS PlugIn</option>
                      <option className="bg-card text-foreground" value="vc_model">VC Model</option>
                      <option className="bg-card text-foreground" value="ns_model">NS Model</option>
                      <option className="bg-card text-foreground" value="etc">etc</option>
                    </select>
                  </div>

                  {formData.type === "vc_model" ? (
                    <div>
                      <label className="block text-xs font-semibold text-foreground mb-2">모델 타입</label>
                      <select
                        name="modelType"
                        value={formData.modelType || "component"}
                        onChange={handleInputChange}
                        className="w-full bg-input text-foreground px-3.5 py-2.5 rounded-xl border border-black/[0.08] dark:border-white/[0.08] focus:bg-background focus:ring-2 focus:ring-primary/20 focus:border-primary outline-none transition-all text-xs"
                      >
                        <option className="bg-card text-foreground" value="component">컴포넌트</option>
                        <option className="bg-card text-foreground" value="layout">레이아웃</option>
                      </select>
                    </div>
                  ) : (
                    <div>
                      <label className="block text-xs font-semibold text-foreground mb-2">초기 버전</label>
                      <input
                        type="text"
                        name="version"
                        value={formData.version}
                        onChange={handleInputChange}
                        className="w-full bg-input text-foreground px-3.5 py-2.5 rounded-xl border border-black/[0.08] dark:border-white/[0.08] focus:bg-background focus:ring-2 focus:ring-primary/20 focus:border-primary outline-none transition-all text-xs font-mono"
                      />
                      {errors.version && (
                        <p className="text-red-500 mt-1 text-[11px]">{errors.version}</p>
                      )}
                    </div>
                  )}
                </div>

                <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                  <div>
                    <label className="block text-xs font-semibold text-foreground mb-2">파일명 / 컴포넌트명</label>
                    <input
                      type="text"
                      name="componentName"
                      value={formData.componentName}
                      onChange={handleInputChange}
                      placeholder="컴포넌트 이름을 입력하세요"
                      className="w-full bg-input text-foreground px-3.5 py-2.5 rounded-xl border border-black/[0.08] dark:border-white/[0.08] focus:bg-background focus:ring-2 focus:ring-primary/20 focus:border-primary outline-none transition-all text-xs"
                    />
                    {errors.componentName && (
                      <p className="text-red-500 mt-1 text-[11px]">{errors.componentName}</p>
                    )}
                  </div>

                  {formData.type === "vc_model" && (
                    <div>
                      <label className="block text-xs font-semibold text-foreground mb-2">초기 버전</label>
                      <input
                        type="text"
                        name="version"
                        value={formData.version}
                        onChange={handleInputChange}
                        className="w-full bg-input text-foreground px-3.5 py-2.5 rounded-xl border border-black/[0.08] dark:border-white/[0.08] focus:bg-background focus:ring-2 focus:ring-primary/20 focus:border-primary outline-none transition-all text-xs font-mono"
                      />
                      {errors.version && (
                        <p className="text-red-500 mt-1 text-[11px]">{errors.version}</p>
                      )}
                    </div>
                  )}
                </div>

                <div>
                  <label className="block text-xs font-semibold text-foreground mb-2">주요 기능</label>
                  <textarea
                    value={formData.features}
                    onChange={(e) => handleFeatureChange(e.target.value)}
                    placeholder="주요 기능을 입력하세요. (줄바꿈 가능)"
                    className="w-full bg-input text-foreground px-3.5 py-2.5 rounded-xl border border-black/[0.08] dark:border-white/[0.08] focus:bg-background focus:ring-2 focus:ring-primary/20 focus:border-primary outline-none transition-all min-h-[90px] resize-y text-xs placeholder-muted leading-relaxed"
                  />
                </div>
              </div>
            </div>

            {/* 2. 파일 업로드 */}
            <div key={formData.type} className="rounded-2xl bg-black/[0.02] dark:bg-white/[0.02] border border-black/[0.05] dark:border-white/[0.06] p-6 space-y-5">
              <div className="mb-1">
                <span className="text-xs font-bold uppercase tracking-wider text-muted">파일 업로드</span>
              </div>

              {/* 소스/실행 파일 */}
              <div>
                <label className="block text-xs font-semibold text-foreground mb-1.5">
                  {formData.type === "vc_model" 
                    ? "VCMX 파일 (필수)" 
                    : formData.type === "vc_plugin"
                      ? "설치파일 (필수)"
                      : "파일 (필수)"}
                </label>
                <input
                  type="file"
                  name="sourceFile"
                  onChange={handleFileChange}
                  className="w-full bg-input text-foreground px-3 py-2 rounded-xl border border-black/[0.08] dark:border-white/[0.08] focus:ring-2 focus:ring-primary/20 outline-none transition-all text-xs file:mr-3 file:py-1 file:px-3 file:rounded-lg file:border-0 file:text-[11px] file:font-semibold file:bg-primary file:text-white hover:file:bg-primary-hover file:transition-colors cursor-pointer"
                />
                {formData.sourceFile && (
                  <p className="text-emerald-500 font-medium mt-1.5 text-[11px]">
                    ✓ {(formData.sourceFile as File).name} 파일이 선택되었습니다.
                  </p>
                )}
                {errors.sourceFile && (
                  <p className="text-red-500 mt-1 text-[11px]">{errors.sourceFile}</p>
                )}
                <p className="text-muted text-[11px] mt-1.5">
                  {formData.type === "vc_model" 
                    ? ".vcmx 파일을 업로드해 주세요." 
                    : formData.type === "ns_model" || formData.type === "etc"
                      ? "모든 확장자의 파일을 업로드할 수 있습니다."
                      : "모든 확장자의 파일을 업로드할 수 있습니다. (미등록 시 기본 썸네일 제공)"}
                </p>
              </div>

              {/* FBX 파일 (VC Model 전용) */}
              {formData.type === "vc_model" && (
                <div>
                  <label className="block text-xs font-semibold text-foreground mb-1.5">
                    FBX 파일 (선택)
                  </label>
                  <input
                    type="file"
                    name="fbxFile"
                    accept=".fbx"
                    onChange={handleFileChange}
                    className="w-full bg-input text-foreground px-3 py-2 rounded-xl border border-black/[0.08] dark:border-white/[0.08] focus:ring-2 focus:ring-primary/20 outline-none transition-all text-xs file:mr-3 file:py-1 file:px-3 file:rounded-lg file:border-0 file:text-[11px] file:font-semibold file:bg-primary file:text-white hover:file:bg-primary-hover file:transition-colors cursor-pointer"
                  />
                  {formData.fbxFile && (
                    <p className="text-emerald-500 font-medium mt-1.5 text-[11px]">
                      ✓ {(formData.fbxFile as File).name} 파일이 선택되었습니다.
                    </p>
                  )}
                  <p className="text-muted text-[11px] mt-1.5">
                    FBX 파일을 업로드하면 3D 뷰어 및 자동 썸네일 생성이 지원됩니다.
                  </p>
                </div>
              )}

              {/* 추가 파일 (선택사항) */}
              <div className="pt-1">
                <label className="block text-xs font-semibold text-foreground mb-1.5 flex items-center justify-between">
                  <span>추가 파일 (선택사항)</span>
                  <span className="text-[11px] text-primary font-normal">복수 파일 선택 가능</span>
                </label>
                <input
                  type="file"
                  multiple
                  onChange={handleAdditionalFilesChange}
                  className="w-full bg-input text-foreground px-3 py-2 rounded-xl border border-black/[0.08] dark:border-white/[0.08] focus:ring-2 focus:ring-primary/20 outline-none transition-all text-xs file:mr-3 file:py-1 file:px-3 file:rounded-lg file:border-0 file:text-[11px] file:font-semibold file:bg-primary file:text-white hover:file:bg-primary-hover file:transition-colors cursor-pointer"
                />
                <p className="text-muted text-[11px] mt-1.5">
                  매뉴얼(PDF), 패치 파일, 예제 소스 등 추가로 제공할 파일들을 여러 개 등록할 수 있습니다.
                </p>

                {/* 선택된 추가 파일 목록 UI */}
                {formData.additionalFiles && formData.additionalFiles.length > 0 && (
                  <div className="mt-2.5 space-y-1.5 max-h-[140px] overflow-y-auto pr-1">
                    {formData.additionalFiles.map((file, idx) => (
                      <div
                        key={`${file.name}_${idx}`}
                        className="flex items-center justify-between px-3 py-2 rounded-lg bg-card border border-black/[0.04] dark:border-white/[0.06] text-xs text-foreground shadow-2xs"
                      >
                        <div className="flex items-center gap-2 truncate pr-2">
                          <span className="truncate font-medium">{file.name}</span>
                          <span className="text-muted shrink-0 font-mono text-[11px]">
                            ({file.size / 1024 < 1024 ? `${(file.size / 1024).toFixed(1)} KB` : `${(file.size / (1024 * 1024)).toFixed(2)} MB`})
                          </span>
                        </div>
                        <button
                          type="button"
                          onClick={() => handleRemoveAdditionalFile(idx)}
                          className="text-muted hover:text-rose-500 font-bold px-1.5 py-0.5 rounded transition-colors shrink-0 cursor-pointer"
                          title="파일 삭제"
                        >
                          <X className="w-3.5 h-3.5" />
                        </button>
                      </div>
                    ))}
                  </div>
                )}
              </div>
            </div>

            {/* 3. 썸네일 설정 */}
            {formData.sourceFile && (
              <div className="rounded-2xl bg-black/[0.02] dark:bg-white/[0.02] border border-black/[0.05] dark:border-white/[0.06] p-6 space-y-5">
                <div className="flex items-center justify-between mb-1">
                  <span className="text-xs font-bold uppercase tracking-wider text-muted">썸네일 설정</span>
                  {formData.type === "vc_plugin" && (
                    <span className="bg-rose-500/10 text-rose-500 dark:text-rose-400 text-[11px] px-2.5 py-0.5 rounded-full font-bold">
                      동영상 썸네일 필수 (MP4 / WebM)
                    </span>
                  )}
                </div>

                {formData.type === "vc_plugin" && (
                  <div className="p-3 bg-primary/10 border border-primary/20 rounded-xl text-xs leading-relaxed text-foreground">
                    <div className="font-bold text-primary flex items-center gap-1.5 mb-0.5">
                      <span>VC PlugIn 동영상 썸네일 안내</span>
                    </div>
                    <p className="text-muted">
                      VC PlugIn 등록 시에는 MP4 또는 WebM 동영상 썸네일을 반드시 업로드하셔야 정상 등록됩니다.
                    </p>
                  </div>
                )}

                <div className="grid grid-cols-1 md:grid-cols-2 gap-5 items-center">
                  {/* 단일 깔끔한 썸네일 캔버스 (불필요한 이중 테두리 제거) */}
                  <div className="relative w-full aspect-square max-w-[240px] mx-auto bg-slate-100 dark:bg-slate-900/60 rounded-xl overflow-hidden border border-black/[0.06] dark:border-white/[0.06] flex items-center justify-center shadow-inner">
                    {thumbnailPreview ? (
                      <>
                        {(formData.thumbnail && isSupportedVideoFile(formData.thumbnail)) || (!formData.thumbnail && isVideoThumbnail(thumbnailPreview)) ? (
                          <VideoThumbnail
                            src={thumbnailPreview}
                            alt="동영상 썸네일 미리보기"
                            controls={true}
                            previewOnHover={false}
                          />
                        ) : (
                          <Image
                            src={thumbnailPreview}
                            alt="썸네일"
                            fill
                            unoptimized
                            className="object-cover"
                          />
                        )}
                        <button
                          type="button"
                          onClick={() => {
                            setThumbnailPreview(null);
                            setFormData((prev) => ({
                              ...prev,
                              thumbnail: null,
                            }));
                          }}
                          className="absolute top-2 right-2 bg-rose-500/90 text-white rounded-full w-6 h-6 flex items-center justify-center hover:bg-rose-600 transition-colors shadow-lg backdrop-blur-sm z-30 cursor-pointer"
                        >
                          <X className="w-3.5 h-3.5" />
                        </button>
                      </>
                    ) : formData.fbxFile ? (
                      <div className="w-full h-full relative">
                        <FbxThumbnailGenerator
                          ref={fbxGenRef}
                          fbxFile={formData.fbxFile as File}
                          onThumbnailGenerated={(dataUrl: string) => {
                            setAutoGeneratedThumbnail(dataUrl);
                            
                            // base64를 File 객체로 변환하여 formData에 설정
                            const arr = dataUrl.split(',');
                            const mime = arr[0].match(/:(.*?);/)?.[1];
                            const bstr = atob(arr[1]);
                            let n = bstr.length;
                            const u8arr = new Uint8Array(n);
                            while (n--) {
                              u8arr[n] = bstr.charCodeAt(n);
                            }
                            const file = new File([u8arr], `thumbnail_${Date.now()}.png`, { type: mime });
                            
                            setFormData(prev => ({
                              ...prev,
                              thumbnail: file
                            }));
                          }}
                        />
                        {autoGeneratedThumbnail && (
                          <div className="absolute inset-0 bg-black/60 flex flex-col items-center justify-center z-10 p-2">
                            <div className="relative w-full h-full">
                              <Image 
                                src={autoGeneratedThumbnail} 
                                fill
                                className="object-cover border-2 border-primary rounded-lg" 
                                alt="생성된 썸네일"
                              />
                            </div>
                            <div className="absolute bottom-2 right-2 z-20">
                              <button
                                type="button"
                                onClick={() => {
                                  setAutoGeneratedThumbnail(null);
                                  setFormData(prev => ({ ...prev, thumbnail: null }));
                                }}
                                className="bg-rose-600 hover:bg-rose-500 text-white text-[11px] font-medium px-2.5 py-1.5 rounded-lg shadow-lg border border-rose-400/50 transition-all active:scale-95 cursor-pointer"
                                title="캡처된 썸네일 삭제하고 다시 3D 뷰어로 돌아가기"
                              >
                                캡처 삭제
                              </button>
                            </div>
                          </div>
                        )}
                        {!autoGeneratedThumbnail && (
                          <div className="absolute bottom-2 right-2 z-20">
                            <button
                              type="button"
                              onClick={() => fbxGenRef.current?.generateThumbnail()}
                              className="bg-primary hover:bg-primary-hover text-white text-[11px] font-medium px-2.5 py-1.5 rounded-lg shadow-xs flex items-center gap-1 transition-all active:scale-95 cursor-pointer"
                              title="현재 각도로 썸네일 캡처"
                            >
                              썸네일 캡처
                            </button>
                          </div>
                        )}
                      </div>
                    ) : (
                      <div className="flex flex-col items-center justify-center opacity-70 p-4">
                        <Image
                          src={
                            formData.type === "vc_plugin" ||
                            formData.type === "vc_model"
                              ? "/images/ic-vc.png"
                              : formData.type === "ns_plugin" ||
                                formData.type === "ns_model"
                              ? "/images/ic-ns.png"
                              : "/images/ic-etc.png"
                          }
                          alt="기본 썸네일"
                          width={64}
                          height={64}
                          className="mb-2 object-contain opacity-65 invert dark:invert-0 dark:opacity-90"
                        />
                        <span className="text-xs text-muted font-medium tracking-wide">
                          시스템 썸네일 자동 적용
                        </span>
                      </div>
                    )}
                  </div>

                  {/* 오른쪽: 직접 썸네일 업로드 섹션 */}
                  <div className="flex flex-col justify-center space-y-2">
                    <h4 className="text-foreground font-semibold text-xs flex items-center gap-1.5">
                      <span>직접 썸네일 설정</span>
                      {formData.type === "vc_plugin" ? (
                        <span className="text-rose-500 text-[10px] font-bold bg-rose-500/10 px-2 py-0.5 rounded">
                          동영상 필수
                        </span>
                      ) : (
                        <span className="text-muted text-[11px] font-normal">(선택)</span>
                      )}
                    </h4>
                    <p className="text-muted text-xs leading-relaxed">
                      {formData.type === "vc_plugin" 
                        ? "VC PlugIn 타입은 MP4 또는 WebM 동영상 파일 업로드가 필수입니다."
                        : `직접 이미지를 업로드하지 않으면 ${formData.fbxFile ? '캡처본' : '기본 아이콘'}이 썸네일로 사용됩니다.`}
                    </p>
                    
                    <div className="relative pt-1">
                      <input
                        type="file"
                        id="thumbnail-upload"
                        name="thumbnail"
                        accept={formData.type === "vc_plugin" ? "video/mp4,video/webm" : "image/*"}
                        onChange={handleFileChange}
                        className="hidden"
                      />
                      <label 
                        htmlFor="thumbnail-upload"
                        className={`w-full cursor-pointer p-3 rounded-xl border transition-all text-xs flex items-center justify-between group ${
                          formData.type === "vc_plugin" && !formData.thumbnail
                            ? "bg-primary/10 border-primary/40 text-primary"
                            : "bg-input hover:bg-card-hover text-foreground border-black/[0.08] dark:border-white/[0.08]"
                        }`}
                      >
                        <span className="truncate">{formData.thumbnail ? formData.thumbnail.name : (formData.type === "vc_plugin" ? '동영상 파일 선택 (MP4, WebM)' : '파일을 선택하세요')}</span>
                        <span className="bg-primary group-hover:bg-primary-hover px-2.5 py-1 rounded-lg text-[10px] text-white shrink-0 ml-2 font-medium">파일 찾기</span>
                      </label>
                    </div>
                    <p className="text-muted text-[11px]">
                      {formData.type === "vc_plugin" ? "💡 MP4, WebM 동영상 권장" : "💡 1:1 비율 권장"}
                    </p>
                  </div>
                </div>
              </div>
            )}
          </div>

          {/* 하단 모달 푸터 */}
          <div className="px-6 py-4 border-t border-black/[0.06] dark:border-white/[0.08] flex justify-end gap-2.5 shrink-0 bg-card">
            <button
              type="button"
              onClick={onClose}
              disabled={isSubmitting}
              className="px-4 py-2 rounded-xl text-xs font-semibold text-muted hover:text-foreground hover:bg-card-hover transition-colors cursor-pointer"
            >
              취소
            </button>
            <button
              type="submit"
              disabled={isSubmitting}
              className="px-5 py-2 rounded-xl bg-primary hover:bg-primary-hover text-white text-xs font-semibold shadow-xs transition-all active:scale-95 disabled:opacity-50 flex items-center gap-2 cursor-pointer"
            >
              {isSubmitting ? (
                <>
                  <span className="w-3.5 h-3.5 border-2 border-white border-t-transparent rounded-full animate-spin shrink-0" />
                  <span>업로드 중...</span>
                </>
              ) : (
                "등록"
              )}
            </button>
          </div>
        </form>
      </div>
    </div>,
    document.body
  );
};

export default ComponentModal;
